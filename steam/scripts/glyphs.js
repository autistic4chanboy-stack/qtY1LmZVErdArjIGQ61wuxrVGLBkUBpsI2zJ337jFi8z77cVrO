// la lune (croissant) et le soleil
function cercle(test) {
  const L = [];
  for (let y = 0; y < 16; y++) { let s = ''; for (let x = 0; x < 16; x++) s += test(x + 0.5, y + 0.5); L.push(s); }
  return L;
}
